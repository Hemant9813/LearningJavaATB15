package ex_01_Java_Basics;

public class Lab005_Arithmetic_Operators {
    static void main(String[] args) {
        int A=21;
        int B=10;

        System.out.println(A+B);    //Arithmetic operators
        System.out.println(A-B);
        System.out.println(A*B);
        System.out.println(A/B);
        System.out.println(A%B); //modulus




    }
}
