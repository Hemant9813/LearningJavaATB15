package ex_01_Java_Basics;

public class Lab006_Relational_Operators {
    static void main(String[] args) {
        int A=10;
        int B=20;
        System.out.println(A<B);
        System.out.println(A>B);
        System.out.println(A<=B);
        System.out.println(A>=B);
        System.out.println(A==B);
        System.out.println(A!=B);
    }
}
