package ex_01_Java_Basics;

public class Lab004_Constant {
    public static void main(String[] args){
       final int A_A=10;  // By adding final keyword to the variable we can make them constant
       // A=100;        //Naming convention UPPERCASE_WITH_UNDERSCORE
        System.out.println(A_A);

        final float F=3.14f;
        //F=3.22;
        System.out.println(F);
    }
}
